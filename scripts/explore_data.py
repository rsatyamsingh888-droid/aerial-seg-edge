from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path("data/raw")

CLASSES = [ "no-data", "background", "building", "road",  "water", "barren", "forest", "agriculture"]



def find_pairs(split, scene):
    img_dir = ROOT / split / scene / "images_png"
    mask_dir = ROOT / split / scene / "masks_png"
    pairs = []
    for img in sorted(img_dir.glob("*.png")):
        mask = mask_dir / img.name
        if mask.exists():
            pairs.append((img, mask))
    return pairs


def count_classes(pairs):
    counts = np.zeros(len(CLASSES), dtype=np.int64)
    for _, mask_path in pairs:
        mask = np.array(Image.open(mask_path))
        counts += np.bincount(mask.ravel(), minlength=len(CLASSES))
    return counts

def main():
    for split in ["Train", "Val"]:
        for scene in ["Urban", "Rural"]:
            pairs = find_pairs(split, scene)
            print(f"{split} {scene}: {len(pairs)} pairs")

    img_path, mask_path = find_pairs("Train", "Urban")[0]
    image = np.array(Image.open(img_path))
    mask = np.array(Image.open(mask_path))
    print("image:", image.shape, image.dtype)
    print("mask: ", mask.shape, mask.dtype)
    print("mask values:", np.unique(mask))

    lines = [ 
        "# LoveDA data statistics",
        "",
        "Generated by 'scripts/explore_data.py'. Class columns are % of pixels.",
        "", 
        "| Split | Scene | pairs | " + " | ".join(CLASSES) + " |",
        "|---|---|---|" + "---|" * len(CLASSES),

    ]
    for split in ["Train", "Val"]:
        for scene in [ "Urban", "Rural"]:
            pairs = find_pairs(split, scene)
            counts = count_classes(pairs)
            share = 100 * counts / counts.sum()
            cells = " | ".join([f"{s:.1f}" for s in share])
            lines.append(f"| {split} | {scene} | {len(pairs)} | {cells} |")

    out = Path("docs/data_stats.md")
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)



if __name__ == "__main__" :
    main()